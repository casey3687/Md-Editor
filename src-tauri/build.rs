use std::{env, fs, io::Write, path::PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=tauri.conf.json");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR not set"));
    let icon_path = out_dir.join("icon.ico");
    write_minimal_icon(&icon_path).expect("failed to write build icon");

    let windows = tauri_build::WindowsAttributes::new().window_icon_path(&icon_path);
    tauri_build::try_build(tauri_build::Attributes::default().windows_attributes(windows))
        .expect("failed to run tauri-build");
}

fn write_minimal_icon(path: &PathBuf) -> std::io::Result<()> {
    const PNG_BYTES: &[u8] = &[
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48,
        0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00,
        0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x01, 0x73, 0x52, 0x47, 0x42, 0x00,
        0xae, 0xce, 0x1c, 0xe9, 0x00, 0x00, 0x00, 0x04, 0x67, 0x41, 0x4d, 0x41, 0x00, 0x00,
        0xb1, 0x8f, 0x0b, 0xfc, 0x61, 0x05, 0x00, 0x00, 0x00, 0x09, 0x70, 0x48, 0x59, 0x73,
        0x00, 0x00, 0x0e, 0xc3, 0x00, 0x00, 0x0e, 0xc3, 0x01, 0xc7, 0x6f, 0xa8, 0x64, 0x00,
        0x00, 0x00, 0x0d, 0x49, 0x44, 0x41, 0x54, 0x18, 0x57, 0x63, 0xf8, 0xff, 0xff, 0x3f,
        0x03, 0x00, 0x08, 0xfc, 0x02, 0xfe, 0x88, 0x5f, 0x06, 0xe0, 0x00, 0x00, 0x00, 0x00,
        0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
    ];

    let mut file = fs::File::create(path)?;
    file.write_all(&[
        0x00, 0x00, // reserved
        0x01, 0x00, // icon type
        0x01, 0x00, // image count
        0x01, // width
        0x01, // height
        0x00, // color count
        0x00, // reserved
        0x01, 0x00, // color planes
        0x20, 0x00, // bits per pixel
        0x44, 0x00, 0x00, 0x00, // image size
        0x16, 0x00, 0x00, 0x00, // image offset
    ])?;
    file.write_all(PNG_BYTES)?;
    Ok(())
}
